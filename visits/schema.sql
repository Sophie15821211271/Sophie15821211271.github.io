CREATE TABLE IF NOT EXISTS sessions (id TEXT PRIMARY KEY, day TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS daily (day TEXT PRIMARY KEY, visits INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS totals (id INTEGER PRIMARY KEY, total INTEGER NOT NULL);
INSERT OR IGNORE INTO totals VALUES (1, 0);
CREATE TRIGGER IF NOT EXISTS count_visit AFTER INSERT ON sessions BEGIN
  INSERT INTO daily VALUES (NEW.day, 1) ON CONFLICT(day) DO UPDATE SET visits = visits + 1;
  UPDATE totals SET total = total + 1 WHERE id = 1;
END;
